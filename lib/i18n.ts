export function categoryLabel(category: Category, language: Language) {
  return categoryTranslations[category][language];
}

export function categoryFilterLabel(category: Category | "Todos", language: Language) {
  return category === "Todos" ? (language === "es" ? "Todos" : "All") : categoryLabel(category, language);
}

export function localizedProduct(product: Product, language: Language) {
  const translation = language === "en" ? productTranslations[product.id] : null;
  return {
    ...product,
    title: translation?.title ?? product.title,
    label: translation?.label ?? product.label,
    description: translation?.description ?? product.description,
    categoryLabel: categoryLabel(product.category, language),
  };
}

export function localizedProjectType(type: string, language: Language) {
  if (language === "es") return type;
  return {
    "Diseño sonoro / corto": "Sound design / short film",
    "Foley / audiovisual": "Foley / audiovisual",
    "Creación de efectos": "Effects creation",
  }[type] ?? type;
}
